import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, unlink, readdir } from 'node:fs/promises';
import postcss from 'postcss';
import { createHash } from 'node:crypto';

// Embed saved summaries for direct file:// use as well as static hosting.
const snapshots = (await readdir('openeval_snapshots/benchmark')).filter(file => file.endsWith('.json')).sort();
const imports = snapshots.map((file, index) => `import snapshot${index} from "../../openeval_snapshots/benchmark/${file}";`);
await writeFile('openeval_tools_src/data/snapshots.ts', [
  '// Generated by scripts/build-tools.mjs from openeval_snapshots/benchmark/*.json.',
  'import type { OEMeasurement } from "./types";',
  ...imports,
  'export const benchmarkSnapshots: Record<string, { benchmark: string; computedAt: string; measurements: OEMeasurement[] }> = {',
  ...snapshots.map((file, index) => `  ${JSON.stringify(file.slice(0, -5))}: snapshot${index},`),
  '};', ''
].join('\n'));

const abilities = [];
for (const file of (await readdir('openeval_snapshots/model')).filter(file => file.endsWith('.json')).sort()) {
  const ability = JSON.parse(await readFile(`openeval_snapshots/model/${file}`, 'utf8'));
  const summaryHash = createHash('sha256').update(await readFile(`openeval_snapshots/benchmark/${file}`)).digest('hex');
  if (ability.summarySha256 === summaryHash) abilities.push(file);
  else console.warn(`Skipping stale ability estimate: ${file}; recompute it with scripts/compute-ability.py.`);
}
await writeFile('openeval_tools_src/data/abilities.ts', [
  '// Generated from corrected-data ability estimates by scripts/build-tools.mjs.',
  'import type { AbilitySnapshot } from "./ability-types";',
  ...abilities.map((file, i) => `import ability${i} from "../../openeval_snapshots/model/${file}";`),
  'export const abilitySnapshots: Record<string, AbilitySnapshot> = {',
  ...abilities.map((file, i) => `  ${JSON.stringify(file.slice(0, -5))}: ability${i},`),
  '};', ''
].join('\n'));

const distributions = [];
for (const file of (await readdir('openeval_snapshots/landscape')).filter(file => file.endsWith('.json')).sort()) {
  const saved = JSON.parse(await readFile(`openeval_snapshots/landscape/${file}`, 'utf8'));
  const hash = createHash('sha256').update(await readFile(`openeval_snapshots/benchmark/${file}`)).digest('hex');
  if (saved.summarySha256 === hash && saved.method === "rasch-1pl-map") distributions.push(file);
  else console.warn(`Skipping stale item distribution: ${file}`);
}
await writeFile('openeval_tools_src/data/landscape.ts', [
  '// Generated corrected item distributions.',
  ...distributions.map((file, i) => `import distribution${i} from "../../openeval_snapshots/landscape/${file}";`),
  'export const landscapeSnapshots: Record<string, {computedAt: string; metrics: Record<string, {bins: number[]; min: number; max: number; items: number; archivedItems: number; models: number; median: number | null}>}> = {',
  ...distributions.map((file, i) => `  ${JSON.stringify(file.slice(0,-5))}: distribution${i},`),
  '};', ''
].join('\n'));

await build({
  entryPoints: ['openeval_tools_src/landscape.tsx', 'openeval_tools_src/benchmark.tsx', 'openeval_tools_src/model.tsx', 'openeval_tools_src/overview.tsx'],
  bundle: true, outdir: 'assets/js/bundles', format: 'iife', jsx: 'automatic', target: ['es2020'],
  minify: false, legalComments: 'linked', define: { 'process.env.NODE_ENV': '"production"' },
  logOverride: { 'ignored-bare-import': 'silent' },
  plugins: [{
    name: 'coverage-snapshot',
    setup(build) {
      build.onLoad({ filter: /[/\\]openeval_snapshots[/\\]coverage\.jsonl$/ }, async ({ path }) => {
        const history = (await readFile(path, 'utf8')).trimEnd();
        if (!history) throw new Error('coverage.jsonl must contain at least one snapshot');
        return { contents: history.slice(history.lastIndexOf('\n') + 1), loader: 'json' };
      });
    }
  }]
});
execFileSync(process.execPath, ['node_modules/@tailwindcss/cli/dist/index.mjs',
  '-i', 'openeval_tools_src/tools.css', '-o', 'tools.tmp.css', '--minify'], {stdio: 'inherit'});
const css = postcss.parse(await readFile('tools.tmp.css', 'utf8'));
css.walkAtRules('layer', rule => {
  if (rule.nodes) rule.replaceWith(...rule.nodes);
  else rule.remove();
});
// Scope utilities so class names like .container and .border cannot affect the host pages.
css.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map(selector => {
    if (selector === ':root' || selector === ':host') return '.oe-tool';
    return '.oe-tool ' + selector;
  });
});
await writeFile('assets/css/tools.css', css.toString());
await unlink('tools.tmp.css');

// Embed the single people source for local-file use as well as static hosting.
const people = JSON.parse(await readFile('openeval_snapshots/contributors.json', 'utf8'));
if (!Array.isArray(people)) throw new Error('contributors.json must contain an array');
for (const person of people) {
  if (!['data', 'contact', 'ack'].includes(person.section)) {
    throw new Error(`Unknown contributor section for ${person.name}: ${person.section}`);
  }
}
const contributionPage = await readFile('contribution.html', 'utf8');
await writeFile('contribution.html', contributionPage.replace(
  /(<script id="contributors-data" type="application\/json">)[\s\S]*?(<\/script>)/,
  (_, open, close) => open + JSON.stringify(people).replace(/</g, '\\u003c') + close
));
